#!/bin/sh
# Make the icon data of the engine from one release of Lucide: the file
# crates/engine/icons/lucide.tsv and the licence file
# crates/engine/icons/LICENSE. The decision is
# docs/decisions/0033-surface-icons.md.
#
# Usage: scripts/lucide-icons.sh [<archive>]
#
#   <archive>  The source archive of the Lucide release. With no archive,
#              the script downloads it from GitHub. The script stops if the
#              SHA-256 of the archive is not the value below.
#
# The script needs curl (only with no archive), tar, awk, and jq. Run it
# again only to change the Lucide version: change VERSION and SHA256 first.
# The version is the version of the icons of the GUI toolkit
# (gpui-kit-assets), so that the window and the key faces use the same
# drawings. See docs/kb/ui-research.md.
#
# The format of lucide.tsv is one record on each line, with the fields
# separated by a tab:
#
#   category <key> <title>
#   icon <name> <category key> <tags, separated by commas> <SVG elements>
#
# A line that starts with "#" is a comment. The category of an icon is the
# first category of its metadata. The SVG elements are the children of the
# element <svg> of the icon file, on one line. All Lucide icons have the same
# element <svg>: a view box of 24 x 24, no fill, a stroke of width 2 in the
# current colour, and round ends and joins. The engine adds it again.

set -eu

VERSION="1.43.0"
SHA256="d57793fa27a720cf487249940c8d68544c7a0d2ed2a046baad65012a902536ed"
URL="https://api.github.com/repos/lucide-icons/lucide/tarball/$VERSION"
OUT="crates/engine/icons"

fail() {
    echo "lucide-icons.sh: $*" >&2
    exit 1
}

sha256() {
    if command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | cut -d ' ' -f 1
    else
        sha256sum "$1" | cut -d ' ' -f 1
    fi
}

command -v jq >/dev/null 2>&1 || fail "jq is not installed."

root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

if [ $# -ge 1 ]; then
    cp "$1" "$work/lucide.tar.gz"
else
    curl -fsSL -o "$work/lucide.tar.gz" "$URL"
fi
[ "$(sha256 "$work/lucide.tar.gz")" = "$SHA256" ] ||
    fail "the archive does not have the SHA-256 of Lucide $VERSION."

mkdir "$work/src"
tar -xzf "$work/lucide.tar.gz" -C "$work/src" --strip-components 1
src="$work/src"
[ -f "$src/LICENSE" ] || fail "the archive has no LICENSE file."

# Each icon file must have the same element <svg>, because the engine adds
# it again with no attributes of the file.
header='<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" >'

{
    echo "# The icons of Lucide $VERSION (https://lucide.dev), ISC licence: see LICENSE."
    echo "# Do not edit this file. scripts/lucide-icons.sh makes it."
    for file in "$src"/categories/*.json; do
        key="$(basename "$file" .json)"
        printf 'category\t%s\t%s\n' "$key" "$(jq -r '.title' "$file")"
    done
    for file in "$src"/icons/*.svg; do
        name="$(basename "$file" .svg)"
        meta="${file%.svg}.json"
        [ -f "$meta" ] || fail "$name has no metadata."
        line="$(jq -r '[(.categories[0] // ""), ((.tags // []) | join(","))] | @tsv' "$meta")"
        body="$(awk -v header="$header" -v name="$name" '
            BEGIN { inside = 0; open = "" }
            # Collect the element <svg> until its ">".
            inside == 0 {
                open = open (open == "" ? "" : " ") $0
                if ($0 ~ />[ \t]*$/) {
                    gsub(/[ \t]+/, " ", open)
                    if (open != header) {
                        print "lucide-icons.sh: " name " has a different element <svg>" > "/dev/stderr"
                        exit 1
                    }
                    inside = 1
                }
                next
            }
            /<\/svg>/ { exit }
            {
                gsub(/^[ \t]+|[ \t]+$/, "")
                body = body (body == "" || body ~ />$/ ? "" : " ") $0
            }
            END { print body }
        ' "$file")"
        case "$body" in
            *"	"*) fail "$name has a tab in its elements." ;;
            "") fail "$name has no elements." ;;
        esac
        printf 'icon\t%s\t%s\t%s\n' "$name" "$line" "$body"
    done
} > "$work/lucide.tsv"

mkdir -p "$root/$OUT"
cp "$work/lucide.tsv" "$root/$OUT/lucide.tsv"
cp "$src/LICENSE" "$root/$OUT/LICENSE"
echo "lucide-icons.sh: $(grep -c '^icon' "$root/$OUT/lucide.tsv") icons in $OUT/lucide.tsv"
